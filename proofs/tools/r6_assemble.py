"""Assemble the rung-6a kit module from the kernel-checked kit case runs/r6-kit/kG.

    python tools/r6_assemble.py      -> Lane4/AGateKit.lean, Lane4/AGateAll.lean
"""
import glob, json, os
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = lambda p: open(os.path.join(HERE, p), encoding="utf-8").read()


def passing(case):
    for p in sorted(glob.glob(os.path.join(HERE, "runs", "r6-kit", case, "attempts", "*.json"))):
        if json.load(open(p, encoding="utf-8")).get("pass"):
            return open(p[:-5] + ".lean", encoding="utf-8").read()
    raise SystemExit("no passing attempt for " + case)


def body(text):
    return "\n".join(l for l in text.splitlines() if l.strip() not in ("namespace Lane4.Case", "end Lane4.Case")).strip() + "\n"


kit = '''/-
the proofs study, rung 6a lemma kit: approximate dot products under additive weight perturbation and
the position-bias gap. Assembled by tools/r6_assemble.py from kit case runs/r6-kit/kG2
(statements by the study team, proofs by a Sonnet doctor, checked by the study team's checker).
Fixed by the study team; doctors do not edit this file. What you need is at the END of the file.
-/
import Lane4.AGate

namespace Lane4.AGate
open Lane4.RSeq (Vec pdot)
open Lane4.RSoft

''' + body(R("runs/r6-kit/kG2/Spec.lean")).replace("open Lane4.RSeq (Vec pdot)\n", "").replace("open Lane4.RSoft Lane4.AGate\n", "") + "\n" + \
    body(passing("kG2")).replace("open Lane4.RSeq (Vec pdot)\n", "").replace("open Lane4.RSoft Lane4.AGate\n", "") + '''
/-! ### What doctors use

`dotQ r xh` is the IDEAL dot product: written weights times an ideal vector, no
perturbation and no rounding. `Close x xh e X` says the actual vector `x` is within `e` of
the ideal `xh` entrywise and `xh` is bounded by `X`. The three lemmas `ardot_near`,
`pdot_near`, `bias_gap`, `ardot_near_abs` (statements `ArdotNear`, `PdotNear`, `BiasGap`, `ArdotNearAbs` above; prefer `ardot_near_abs` for rows with few non-zero weights) each give an
error bound AND a magnitude bound; the magnitude bound is what you need to show that later
`fl` arguments are within `M`. -/

end Lane4.AGate
'''
open(os.path.join(HERE, "Lane4", "AGateKit.lean"), "w", encoding="utf-8", newline="\n").write(kit)
allf = '''/-
the proofs study, rung 6a: everything a case file imports (the gated framework and its kit, the
rung-5 softmax kit, and the binary32 instance with the side conditions used by the two
corollaries in every case's Final.lean). Fixed by the study team.
-/
import Lane4.AGateKit
import Lane4.RSoftAll
'''
open(os.path.join(HERE, "Lane4", "AGateAll.lean"), "w", encoding="utf-8", newline="\n").write(allf)
print("assembled AGateKit.lean (%d lines), AGateAll.lean" % kit.count("\n"))
