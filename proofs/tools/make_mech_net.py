"""Mechanism row (b), PREREG_MECH.md: the per-network Lean file for the EXTRACTED program.

    python tools/make_mech_net.py <run dir> [--net W14.json] [--radius 1/16384] [--tag name] [--no-trained]
        -> runs/mech/<tag>/Net.lean, runs/mech/<tag>/meta.json

1. tools/mech_extract.py reads a program off the skeleton's weights (it is not given the task).
2. The frozen rung-8 mirror (tools/r8_cert.py, unchanged; only the task it is handed is replaced, in this
   process, by the extracted program) builds the certificate for `check8 δ net prog cert`.
3. The file proves, with `decide +kernel` for every closed Boolean: `accept`; from Lane4.R8K.sound8 as it stands
   `skeleton_ok`, `exact_all_lengths`, `binary32`, and (unless --no-trained) `trained_exact_all_lengths`,
   `trained_binary32`, all against `ptarget = prog.target`; and, if the program is bisimilar to the registered
   task-A automaton, `prog_is_task : ptarget w i = target w i` through the study team's lemma Lane4/MechBisim.lean,
   whose text is included in the file (no module is added to the build).
If the extraction fails, no Lean file is written and meta.json says why. RUN UNDER reservation wrapper.
Imports the frozen generator tools/make_r8_net.py for its text templates; edits nothing.
"""
import json, os, sys
from fractions import Fraction as F

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(HERE, "tools"))
import make_r8_net as M8, r8_cert as C8, r7_cert as RC, mech_extract as MX
import make_r7_ka as KA, make_r7_cases as MC, make_r7_net as M7, r7

q, nl, arg = KA.q, "\n", M8.arg
TASK_A = (0, (lambda s, t: t - 1), (lambda s, t: ((t - 1) + s) % 5))


def bisim(prog, other, ntok):
    """Reachable pairs of the product, or None if two outputs differ."""
    s0, step, outp = other
    start = (prog["init"], s0)
    seen, todo = [start], [start]
    while todo:
        a, b = todo.pop()
        for t in range(1, ntok + 1):
            if prog["out"][a][t - 1] != outp(b, t): return None
            nx = (prog["step"][a][t - 1], step(b, t))
            if nx not in seen: seen.append(nx); todo.append(nx)
    return seen


def lean_bisim_text():
    s = open(os.path.join(HERE, "Lane4", "MechBisim.lean"), encoding="utf-8").read()
    return s[s.index("namespace Lane4.Mech"):s.index("end Lane4.Mech") + len("end Lane4.Mech")]


def main():
    d = os.path.abspath(sys.argv[1])
    tj = json.load(open(os.path.join(d, "train.json")))
    netf = arg("--net", "W14.json")
    delta = F(arg("--radius", "1/16384"))
    with_trained = "--no-trained" not in sys.argv
    W = json.load(open(netf if os.path.isabs(netf) else os.path.join(d, netf)))
    T = json.load(open(os.path.join(d, "T.json")))
    tag = arg("--tag", "%s-%s-s%d" % (tj["task"], tj["recipe"], tj["seed"]))
    out = os.path.join(HERE, "runs", "mech", tag)
    os.makedirs(out, exist_ok=True)
    dq = q(delta)
    meta = dict(tag=tag, dir=os.path.relpath(d, HERE).replace(os.sep, "/"), net=os.path.basename(netf), radius=str(delta),
                seed=tj["seed"], recipe=tj["recipe"])
    ok, why, prog, info = MX.extract(W, delta)
    meta.update(extract_ok=ok, extract_reason=why, **info)
    if not ok:
        json.dump(meta, open(os.path.join(out, "meta.json"), "w"), indent=1)
        print(tag, "extraction FAILED |", why); return
    meta["program"] = prog
    RC.task_dfa = lambda name: (prog["init"], (lambda s, t: prog["step"][s][t - 1]), (lambda s, t: prog["out"][s][t - 1]))
    mok, mwhy, minfo = C8.check(W, "extracted", delta)
    cert = minfo.pop("cert")
    pairs = bisim(prog, TASK_A, prog["ntok"]) if prog["ntok"] == 5 else None
    meta.update(mirror_ok=bool(mok), mirror_reason=mwhy, cert_states=len(cert["states"]), cert_rows=minfo.get("table_rows"),
                is_task_A=pairs is not None, five_state_program=(prog["step"] == [[0, 1, 2, 3, 4]] * 5 and
                                                                  prog["out"] == [[(s + t) % 5 for t in range(5)] for s in range(5)]))
    LL = lambda M: "[" + ", ".join("[" + ", ".join(str(v) for v in r) + "]" for r in M) + "]"
    L = ["import Lane4.R8Glue" if not mok else "import Lane4.R8All", "", "/-",
         "the proofs study, mechanism row (b) for rung 8 (PREREG_MECH.md). Generated by tools/make_mech_net.py; no hand edits.",
         "network: %s (%s), radius %s" % (meta["dir"], meta["net"], dq),
         "program: read off the weights by tools/mech_extract.py (the finder is not given the task): %d states, %d rows"
         % (info["program_states"], info["program_rows"]),
         "mirror (tools/r8_cert.py with the extracted program as task): %s (%s)" % ("accept" if mok else "reject", mwhy), "-/", "",
         lean_bisim_text(), "",
         "namespace Lane4.Case", "open Lane4.RSeq (Vec)", "open Lane4.RSoft Lane4.AGate", "open Lane4.Seq (Mask cand tokAt)", ""]
    L += MC.task_parts(r7.task("A"))[0] + ["",
          "/-- THE EXTRACTED PROGRAM: `step` and `out` of state `s` on token `t` are row `s`, column `t - 1`. -/",
          "def progStep : List (List ℕ) := " + LL(prog["step"]),
          "def progOut : List (List ℕ) := " + LL(prog["out"]),
          "def prog : Lane4.Cert.Task :=", "  { ntok := %d, init := %d," % (prog["ntok"], prog["init"]),
          "    step := fun s t => (progStep.getD s []).getD (t - 1) 0,",
          "    out := fun s t => (progOut.getD s []).getD (t - 1) 0 }", "",
          "/-- What the program outputs at position `i` of input `w`. -/",
          "def ptarget (w : List ℕ) (i : ℕ) : ℕ := prog.target w i", "",
          (M8.STATEMENT % dict(RAD=dq)).replace("target w i", "ptarget w i"),
          KA.lean_net("net", W), KA.lean_net("trained", T), "end Lane4.Case", "",
          "namespace Lane4.Net", "open Lane4.Case Lane4.Cert Lane4.Cert8 Lane4.AGate Lane4.RSoft Lane4.Bin32",
          "open Lane4.Seq (Mask cand tokAt)", "set_option maxRecDepth 1000000", "set_option maxHeartbeats 0", "",
          "def task : Task := prog", ""]
    b = lambda x: "true" if x else "false"
    nh, ns = len(cert["heads"]), len(cert["states"])
    for k, hc in enumerate(cert["heads"]):
        L.append("def hc%d : HCert :=" % k + nl + "  { cands := [%s], L := %d, spread := %s," % (", ".join(b(x) for x in hc["cands"]), hc["L"], q(hc["spread"]))
                 + nl + "    S := %s," % M8.ivm(hc["S"]) + nl + "    VE := %s," % M8.ivm(hc["VE"]) + nl + "    Bv := %s }" % KA.L(hc["Bv"]))
    for k, (s, wins) in enumerate(cert["states"]):
        L.append("def s%d : ℕ × List (List ℕ) := (%d, [%s])" % (k, s, ", ".join("[" + ", ".join(str(t) for t in wn) + "]" for wn in wins)))
    L.append("def cert : Cert8 :=" + nl + "  { heads := [%s]," % ", ".join("hc%d" % k for k in range(nh)) + nl
             + "    states := [%s] }" % ", ".join("s%d" % k for k in range(ns)))
    L.append("abbrev E : List (List IV) := net.embed.map (embIV (%s))" % dq)
    L.append("")
    names = []
    if not mok:
        L += ["theorem reject : check8 (%s) net task cert = false := by decide +kernel" % dq, "", "end Lane4.Net",
              "#print axioms Lane4.Net.reject", ""]
    else:
        st = lambda k: "(List.range task.ntok).all (fun k => caseOK8 (%s) net netB0 task cert s%d (k + 1))" % (dq, k)
        L.append("theorem rd0 : decide ((0 : ℚ) ≤ %s) = true := by decide +kernel" % dq)
        L.append("theorem rd1 : decide ((%s : ℚ) ≤ 1 / 2) = true := by decide +kernel" % dq)
        L.append("theorem shape : net.shapeOK task.ntok = true := by decide +kernel")
        L.append("theorem wts : weightsOK net netB0 = true := by decide +kernel")
        L.append("theorem len : (cert.heads.length == netB0.heads.length) = true := by decide +kernel")
        L.append("theorem stl : cert.states.all (fun st => st.2.length == netB0.heads.length) = true := by decide +kernel")
        L.append("theorem ini : cert.states.contains (task.init, cert.heads.map (fun hc => if hc.cands.getD 0 false = true then [0] else [])) = true := by decide +kernel")
        for k in range(nh):
            L.append("theorem hd%d : headOK8 (%s) E netH%d hc%d = true := by decide +kernel" % (k, dq, k, k))
        for k in range(ns):
            L.append("theorem st%d : %s = true := by decide +kernel" % (k, st(k)))

        def nest(lemma, nil, nm):
            t = nil
            for x in reversed(nm):
                t = "%s _ _ _ _ _ %s (%s)" % (lemma, x, t) if lemma == "heads_cons" else "%s _ _ _ %s (%s)" % (lemma, x, t)
            return t
        L += ["", "/-- THE CHECKER ACCEPTS the network against the extracted program. -/",
              "theorem accept : check8 (%s) net task cert = true :=" % dq,
              "  check8_of (%s) net task cert netB0 rfl rd0 rd1 shape wts len" % dq,
              "    (%s) stl ini" % nest("heads_cons", "heads_nil _", ["hd%d" % k for k in range(nh)]),
              "    (%s)" % nest("all_cons_of", "all_nil_of _", ["st%d" % k for k in range(ns)])]
        teq = ("theorem target_eq (w : List ℕ) (i : ℕ) (_h1 : 1 ≤ i) (_h2 : i ≤ w.length) :\n"
               "    task.target w i = ptarget w i := rfl")
        tail = M8.TAIL.replace("target w i", "ptarget w i") % dict(RAD=dq, TEQ=teq)
        cut = tail.index("/-! The network exactly as trained. -/")
        L.append(tail if with_trained else tail[:cut])
        names = ["accept", "skeleton_ok", "exact_all_lengths", "binary32"] + (["trained_exact_all_lengths", "trained_binary32"] if with_trained else [])
        L += ["", "end Lane4.Net", ""]
        if pairs is not None:
            L += ["namespace Lane4.NetA", "open Lane4.Case Lane4.Cert Lane4.Cert8 Lane4.AGate Lane4.RSoft Lane4.Bin32", "",
                  "/-- The registered task-A automaton of rung 8 (state: the previous digit). -/",
                  M7.TASKDEF["A"], M8.TEQ["A"], "", "end Lane4.NetA", "",
                  "namespace Lane4.Net", "open Lane4.Case Lane4.Cert", "",
                  "theorem bis : Lane4.Mech.bisimOK prog Lane4.NetA.task [%s] = true := by decide +kernel"
                  % ", ".join("(%d, %d)" % p for p in pairs), "",
                  "/-- THE EXTRACTED PROGRAM IS THE TASK: on every valid input, at every position. -/",
                  "theorem prog_is_task (w : List ℕ) (hw : ∀ t ∈ w, 1 ≤ t ∧ t ≤ 5) (i : ℕ) (h1 : 1 ≤ i) (h2 : i ≤ w.length) :",
                  "    ptarget w i = target w i := by",
                  "  have h := Lane4.Mech.bisim_sound prog Lane4.NetA.task _ bis w hw i h1 h2",
                  "  rw [Lane4.NetA.target_eq w i h1 h2] at h",
                  "  exact h", "", "end Lane4.Net", ""]
            names.append("prog_is_task")
        L += ["#print axioms Lane4.Mech.bisim_sound"] + ["#print axioms Lane4.Net.%s" % n for n in names] + [""]
    open(os.path.join(out, "Net.lean"), "w", encoding="utf-8", newline=nl).write(nl.join(L))
    meta["theorems"] = names
    json.dump(meta, open(os.path.join(out, "meta.json"), "w"), indent=1)
    print(tag, "| extracted program: %d states, %d rows (certificate %d states, %s rows) | mirror: %s | is task A: %s | 5-state program: %s" % (
        info["program_states"], info["program_rows"], len(cert["states"]), minfo.get("table_rows"),
        "accept" if mok else "reject: " + mwhy, pairs is not None, meta["five_state_program"]))


if __name__ == "__main__":
    main()
